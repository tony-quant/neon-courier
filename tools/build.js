// tools/build.js — writes sw.js. The cache name is a hash of every shipped file,
// so any change to the game produces a new cache and the service worker updates cleanly.
// Run with: npm run build   (npm test runs it first)
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const SKIP_DIRS = new Set(['node_modules', 'tests', 'tools', '.git', 'test-results', 'playwright-report']);
const SKIP_FILES = new Set(['sw.js', 'README.md', 'package.json', 'package-lock.json', '.gitignore', 'playwright.config.js']);
const SHIP_EXT = new Set(['.html', '.js', '.css', '.webmanifest', '.png', '.svg']);

function walk(dir, out) {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    const rel = path.relative(ROOT, full).split(path.sep).join('/');
    const st = fs.statSync(full);
    if (st.isDirectory()) {
      if (!SKIP_DIRS.has(name) && !name.startsWith('.')) walk(full, out);
    } else if (!SKIP_FILES.has(name) && SHIP_EXT.has(path.extname(name))) {
      out.push(rel);
    }
  }
  return out;
}

const files = walk(ROOT, []).filter((f) => f !== 'js/version.js');
const hash = crypto.createHash('sha256');
for (const f of files) {
  hash.update(f);
  hash.update(fs.readFileSync(path.join(ROOT, f)));
}
const version = hash.digest('hex').slice(0, 12);

// The version is shown in the game's corner so you can check which build is running.
fs.writeFileSync(path.join(ROOT, 'js', 'version.js'),
  "// GENERATED by tools/build.js. Do not edit.\nwindow.BUILD_VERSION = '" + version + "';\n");

const assets = ['./'].concat(files.concat(['js/version.js']).map((f) => './' + f));

const sw = `// sw.js — GENERATED by tools/build.js. Do not edit by hand.
// Cache-first service worker: the whole game is cached on the first visit, so it runs offline.
// A new build changes VERSION, which installs a fresh cache and removes the old one.
const VERSION = '${version}';
const CACHE = 'platformer-' + VERSION;
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(ASSETS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((k) => k.startsWith('platformer-') && k !== CACHE).map((k) => caches.delete(k))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  if (new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(req, { ignoreSearch: true });
      if (hit) return hit;
      try {
        const res = await fetch(req);
        if (res.ok) cache.put(req, res.clone());
        return res;
      } catch (err) {
        const fallback = await cache.match('./index.html');
        if (fallback && req.mode === 'navigate') return fallback;
        throw err;
      }
    })
  );
});
`;

fs.writeFileSync(path.join(ROOT, 'sw.js'), sw);
console.log('sw.js written: version ' + version + ', ' + assets.length + ' assets');
